package com.jimeng.dataserver.ai.connector.spi;

/**
 * 连接器<b>能力</b>——「它能被怎么用」。与连接器<b>类型</b>（MySQL / HTTP / ES…）正交：
 * 类型是一行，能力是一列，加一种系统 = 加一行，加一种玩法 = 加一列，互不干扰。
 *
 * <p>上层（工具层、主动感知）只面向能力编程，<b>不认识具体类型</b>。
 * 例：问数用到的是 {@link #QUERY} + {@link #DESCRIBE}，它不需要知道底下是 MySQL 还是 Elasticsearch。
 *
 * <p><b>能力不是静态声明就算数的。</b>同一种类型在不同客户那里能力可能不同（客户给的账号若没有读
 * 元数据的权限，DESCRIBE 就得降级）。所以接入时要探测一次、把实际可用的能力回填到实例上，
 * 界面如实显示「这个连接的自描述能力不可用，原因是……」——否则又是一次静默降级。
 */
public enum Capability {

    /** 能查：执行 Agent 自己写的查询语句。平台只做护栏，不理解语句语义。 */
    QUERY,

    /** 能自描述：列目录（有哪些表 / 接口 / 目录 / 主题）+ 看某个对象的结构。 */
    DESCRIBE,

    /** 能调用：执行一次操作（HTTP 请求 / 存储过程 / RPC）。写操作按权限级别决定直接执行还是生成待审批项。 */
    INVOKE,

    /**
     * 能写：执行一次会改变数据的操作。
     *
     * <p><b>它与其它能力有一个本质区别：其余能力由「类型 + 探测」决定，它还要加上
     * 「这条连接的写策略」和「客户给的账号确实能写」。</b>三者的交集才回填 WRITE——
     * 少了任何一个而声明「能写」，都是在骗界面和模型。
     */
    WRITE,

    /** 能同步：批量把内容拉进知识库。<b>不是工具</b>——它是后台任务，在 Agent 运行之外发生。 */
    SYNC,

    /** 能订阅：事件推过来。<b>不是工具</b>——它是触发器。 */
    SUBSCRIBE,

    /** 能报状态：健康探测。框架定期调用，结果写回实例。 */
    HEALTH
}
