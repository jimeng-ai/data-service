package com.jimeng.dataserver.ai.connector.service;

import java.util.Locale;
import java.util.Optional;

/**
 * 一条连接的<b>数据出库档位</b>：为了看懂客户那个库，我们允许多少东西离开它。
 *
 * <h3>为什么是三档，不是一个「许不许读数据」的布尔</h3>
 * 「数据不出域」和「不能读数据」是两件事。把它们并成一个开关，代价有确切的数字：
 * 在同一批<b>真实生产库</b>上，纯元数据推断（Nexus，专为隐私约束设计）F1 0.61 / 精确率 0.49；
 * 允许在库内采样的（Tursio）F1 0.80 / 精确率 <b>1.00</b>。
 * 也就是说，一个字节的数据值都不碰，表关系推断的精确率<b>大约腰斩</b>。
 * 而推错的表关系不会报错——它会让模型 join 出一个看着很正常的错数字，
 * 比「查不出来」难发现得多。
 *
 * <p>所以真正要跟客户谈的不是「读不读数据」，而是<b>「允许什么形态的东西离开这个库」</b>。
 * 那是一条谱，不是一个开关：表名和「这一列 NULL 率 3%」和「这一列的 top-20 实际取值」
 * 三者的敏感度差着数量级，用一个布尔表达，客户只能一刀切到最严的那头，
 * 然后为此付上面那半个精确率。
 *
 * <h3>三档的边界</h3>
 * <ul>
 *   <li>{@link #METADATA_ONLY}：只有名字和形状。</li>
 *   <li>{@link #DERIVED_STATS}（默认）：加上<b>从数据算出来、但不还原成数据</b>的统计量。</li>
 *   <li>{@link #SAMPLE_VALUES}：加上<b>真实取值本身</b>。需要企业超管显式开启。</li>
 * </ul>
 * 每一档「具体什么东西会出库」写在各自的 {@link #egressStatement()} 上，
 * 那句话会随连接详情接口发给客户看，也是 DDL 列注释里的同一句话。
 * <b>改档位的含义就要同步改那句话</b>——安全说明和实现分叉，等于没有安全说明。
 *
 * <h3>★ 这个类的 API 是「问许可」，不是「读数字」</h3>
 * 对外只有 {@link #allowsDerivedStats()} / {@link #allowsSampleValues()} 这样按意图命名的谓词，
 * <b>刻意不暴露任何档位序号</b>。理由很具体：只要调用方拿得到一个整数，迟早有人写出
 * {@code if (tier >= 2)}——而其中一处本该是 {@code >}。那种错不会编译失败、不会跑挂，
 * 它只是让本该留在客户库里的取值多走了一档出去，且没有任何信号。
 * 枚举常量的声明顺序确实是由松到紧递增的，但<b>不要用 {@code ordinal()} / {@code compareTo()} 比较</b>，
 * 要判断就加一个按意图命名的谓词，让新增的判断在这个文件里被看见一次。
 *
 * <h3>★ 兜底方向：两个不同的「不确定」，落点不同</h3>
 * {@link #parse(String)} 有两条兜底，是刻意分开的：
 * <ul>
 *   <li><b>空值 → 默认档</b>（{@link #DEFAULT}）。列是后加的，加列之前建的连接这一格是 NULL，
 *       那不表示客户选过最严的那档，只表示<b>他没选过</b>。把没选过一律压到第 1 档，
 *       等于在一次升级里静默地把所有存量客户的关系推断精确率打对折，而没有任何人会收到通知。</li>
 *   <li><b>认不出来的值 → 最严档</b>（{@link #METADATA_ONLY}）。这一类是「库里有个我不认识的字符串」：
 *       手工改过库、或者某个更新的版本写下了这个版本还不认识的档位。
 *       不认识就必须当最严的处理——<b>往宽的方向兜底就是本仓库反复吃亏的那类静默降级</b>，
 *       而这里降级的后果是客户的真实数据出库。</li>
 * </ul>
 * 两条兜底的共同不变式（也是真正要守的那一条）：
 * <b>{@link #SAMPLE_VALUES} 永远不可能由兜底到达</b>，只能由一个原样匹配的显式取值到达。
 *
 * @see com.jimeng.dataserver.ai.connector.spi.WritePolicy
 *      它管「能不能改<b>客户的数据</b>」，本类管「能带走客户的<b>什么数据</b>」。两道闸互不替代，
 *      也不要合并：只读连接照样可能在第 3 档上把真实取值带出来。
 */
public enum SemanticDataTier {

    /**
     * 第 1 档，纯元数据：<b>表名、列名、数据类型、可空性、索引、外键声明、客户自己写在库里的注释。</b>
     *
     * <p>出库的全部是「结构」，没有任何一条业务记录参与运算。这是可选的最严档，
     * 也是任何认不出来的配置值的落点。
     *
     * <p>代价要说在前面，不能让客户以为这一档是免费的：仅凭名字和类型推表关系，
     * 真实生产库上的精确率约 0.49——<b>推出来的关系里有一半是错的</b>，
     * 而错的那一半不会报错，只会让模型 join 出错数字。选这一档的客户应当同时接受
     * 「表关系要人工确认」这件事。
     */
    METADATA_ONLY,

    /**
     * 第 2 档，派生统计（<b>默认</b>）：在第 1 档之上，允许<b>在客户库内计算</b>、只把结果带出来。
     *
     * <p>会出库的是：某列的 distinct 数、NULL 率、min/max、字符形状（长度分布 / 是否纯数字等）、
     * 两列之间的包含率（LEFT JOIN 命中比例）、基数、以及 minhash sketch
     * ——sketch 是 <b>K 个哈希值，不是原始值</b>。
     *
     * <p><b>这一档不是「不碰数据」，要如实说。</b>聚合结果本身也可能携带信息：
     * 一列 {@code salary} 的 min/max 就是两个真实的薪资数字；一列只有两个 distinct 值时，
     * 「distinct=2」几乎等于把那一列的取值空间说出来了。我们仍把它设为默认，
     * 理由是这一档换来的东西是可度量的（关系推断精确率从约 0.49 到 1.00），
     * <b>而不是因为它「不算数据」</b>。介意的客户可以降到第 1 档，那是他的选择，不是我们替他做的判断。
     */
    DERIVED_STATS,

    /**
     * 第 3 档，样本值（<b>默认关闭，须企业超管显式开启</b>）：在第 2 档之上，允许把
     * <b>真实取值本身</b>带出客户库——某列的 top-k 实际值、低基数列的全量维值索引。
     *
     * <p><b>这一档没有委婉说法：它索引的就是客户库里一行行真实的取值。</b>
     * 「地区」列的维值索引意味着客户所有的地区名进了我们的库；
     * 「客户名称」列的 top-k 意味着最高频的那些真实客户名进了我们的库。
     * 参考实现（Quick BI 的「维值学习」）做的正是这件事，而它的官方数据安全页回避了这一点——
     * <b>我们不照搬这种叙事</b>：这句话要原样出现在列注释、接口文档和给客户的安全说明里。
     *
     * <h3>★ PII 过滤已落地，但它不是一道保险</h3>
     * top-k 样本值天然会把 PII 捞出来——姓名、手机号、地址就躺在高频取值里。
     * {@code SemanticValueProfiler} 现在两道都过：查之前按列名/注释过
     * {@code PiiFilter#screenColumn}（一个叫 phone 的列哪怕当前全空，也仍然是手机号列），
     * 拿到取值之后再按取值形状过 {@code PiiFilter#screenValues}。
     *
     * <p><b>但要如实说清它做不到什么。</b>同类实现给出的 PII 检测指标是 recall 95% / precision 91%，
     * 即<b>大约每 20 个 PII 取值仍会漏掉 1 个</b>。我们的实现刻意偏向召回而不是精确
     *（假阳性的代价是少一个值域，假阴性的代价是客户的手机号进我们的库、再进模型提示词），
     * 但偏向不等于保证。所以这一档仍然默认关闭、仍然需要企业超管显式开启——
     * 它的正当性来自「有人为这件事做过一次决定」，不来自过滤器。
     *
     * <h3>「须企业超管显式开启」这句话今天由谁兑现</h3>
     * 由 {@code ConnectorAdminController} 上那道<b>整类</b>的 {@code superAdminGuard.requireSuperAdmin()}
     * 兜着——连接器管理的每一个端点都在它后面，所以改档位天然需要企业超管，本类不再重复设闸。
     * <b>但这个前提是别人代码里的</b>：哪天新增一条不走那个控制器的连接编辑入口
     *（批量导入、开放 API、给成员用的简化表单），第 3 档就会随之对非超管开放，而且不报错。
     * 新增入口时请连同这一条一起想：<b>这一档的门槛是「谁能改」，不是「改成什么」</b>。
     *
     * <p>本类<b>只负责回答「允不允许」，不负责过滤</b>。两者缺一不可，且顺序固定：
     * 先 {@link #allowsSampleValues()}，再 PII 过滤。今天唯一读取值的路径
     *（{@code SemanticValueProfiler}）两道都接了；<b>将来新增任何读取值的路径，
     * 两道都要重新接一遍</b>——本类的谓词返回 true 只说明「这条连接被授权了」，
     * 它不会替你过滤任何东西。
     */
    SAMPLE_VALUES;

    /**
     * 没有显式选择时的档位。
     *
     * <p>取第 2 档而不是第 1 档，是一次<b>睁着眼睛做的取舍</b>：第 1 档会把表关系推断的精确率
     * 打到约 0.49，而那半数错误关系是静默的。默认值写在这里一处，DDL 注释、接口文档、
     * 空值兜底都引用它。
     *
     * <p>它<b>永远不会是</b> {@link #SAMPLE_VALUES}：真实取值出库只能是一个显式动作。
     */
    public static final SemanticDataTier DEFAULT = DERIVED_STATS;

    /** 认不出来时的落点。永远是最严的那一档。 */
    public static final SemanticDataTier MOST_RESTRICTIVE = METADATA_ONLY;

    /**
     * 宽松解析，给<b>读库里的值</b>用。两条兜底方向不同，见类注释：
     * 空值 → {@link #DEFAULT}（没选过 ≠ 选了最严的）；认不出来 → {@link #MOST_RESTRICTIVE}。
     *
     * <p>不变式：无论传进来什么，都<b>不可能</b>返回 {@link #SAMPLE_VALUES}，
     * 除非它原样就是那个枚举名。
     */
    public static SemanticDataTier parse(String v) {
        if (v == null || v.isBlank()) {
            return DEFAULT;
        }
        return tryParse(v).orElse(MOST_RESTRICTIVE);
    }

    /**
     * 严格解析，给<b>校验接口入参</b>用：只认三个枚举名（忽略大小写与首尾空白），其余一律 empty。
     *
     * <p>为什么入参不能直接用 {@link #parse(String)}：那会把一个拼错的档位<b>悄悄降一档</b>存下去，
     * 界面上显示的还是超管刚才选的那个——一次不报错的配置失效。
     * 库里的脏值必须兜底（没人可问），接口入参必须报错（有人可问），这是两种场景。
     */
    public static Optional<SemanticDataTier> tryParse(String v) {
        if (v == null || v.isBlank()) {
            return Optional.empty();
        }
        try {
            return Optional.of(valueOf(v.trim().toUpperCase(Locale.ROOT)));
        } catch (IllegalArgumentException e) {
            return Optional.empty();
        }
    }

    /**
     * 允不允许把结构（表名 / 列名 / 类型 / 索引 / 客户库注释）带出客户库。
     *
     * <p>恒为 true：不许读结构就等于不许接入，那种连接不该存在，而不是该配成一个档位。
     * 保留这个谓词是为了让调用点把「我要读的是哪一层」写出来，而不是因为它可能返回 false。
     */
    public boolean allowsMetadata() {
        return true;
    }

    /**
     * 允不允许在客户库内做聚合、把<b>派生统计量</b>带出来（distinct 数、NULL 率、min/max、
     * 字符形状、包含率、基数、minhash sketch）。
     *
     * <p>S3 采样验证问的就是这一句：算一条 {@code a.x -> b.y} 的 LEFT JOIN 包含率算派生统计，
     * 允许；把没命中的那些值取回来看看长什么样<b>不算</b>，那是 {@link #allowsSampleValues()}。
     */
    public boolean allowsDerivedStats() {
        return this != METADATA_ONLY;
    }

    /**
     * 允不允许把<b>真实取值</b>带出客户库（top-k 实际值、低基数列的维值索引）。
     *
     * <p>★ 返回 true <b>不等于可以直接读</b>：取值出库前还必须过 PII 过滤。
     * 这个谓词回答的是「这条连接被授权了吗」，不是「这个值可以带走吗」。
     * 任何新增的读取值路径都要自己接上过滤，理由见 {@link #SAMPLE_VALUES} 的注释。
     */
    public boolean allowsSampleValues() {
        return this == SAMPLE_VALUES;
    }

    /** 给人看的短名，带档位序号，界面直接显示。 */
    public String label() {
        return switch (this) {
            case METADATA_ONLY -> "第 1 档 · 纯元数据";
            case DERIVED_STATS -> "第 2 档 · 派生统计";
            case SAMPLE_VALUES -> "第 3 档 · 样本值";
        };
    }

    /**
     * 这一档<b>具体什么东西会离开客户的数据库</b>，一句话，给客户看。
     *
     * <p>做成方法而不是只写在 @Schema 里，是因为这句话要出现在连接详情接口的响应里、
     * 显示在超管改档位的那个界面上。安全说明只躺在开发者才读的注解里，等于没写。
     * 第 3 档那句<b>必须</b>说出「真实取值」四个字——回避这件事的叙事我们不照搬。
     */
    public String egressStatement() {
        return switch (this) {
            case METADATA_ONLY -> "只有表名、列名、数据类型、可空性、索引和客户自己写在库里的注释会离开数据库。"
                    + "不做任何聚合，没有一条业务记录参与运算。代价：仅凭名字推表关系，真实生产库上精确率约 0.49，"
                    + "推出来的关系需要人工确认。";
            case DERIVED_STATS -> "在纯元数据之上，允许在客户库内做聚合、只把算出来的统计量带走："
                    + "distinct 数、NULL 率、min/max、字符形状、两列之间的包含率、基数、minhash sketch"
                    + "（K 个哈希值，不是原始值）。逐行的业务记录不出库。"
                    + "但要如实说明：min/max 本身就是两个真实取值，低基数列的 distinct 数也会透露取值空间的大小。";
            case SAMPLE_VALUES -> "在派生统计之上，允许把【真实取值】本身带出数据库：某列的 top-k 实际值、"
                    + "低基数列的全量维值索引。说白了，「地区」列的维值索引意味着贵司所有地区名进入我们的库，"
                    + "「客户名称」列的 top-k 意味着最高频的真实客户名进入我们的库。"
                    + "这一档默认关闭，只能由企业超管显式开启。取值出库前会过 PII 过滤（按列名与取值形状两道），"
                    + "但如实说明：同类实现的 PII 检测召回率约 95%，即大约每 20 个 PII 取值仍可能漏掉 1 个，"
                    + "过滤是减损手段，不是保证。";
        };
    }
}
